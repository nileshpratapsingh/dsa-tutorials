vector<int> merge_sort(vector<int> &arr) {
    if (arr.size() <= 1) {
        return arr;
    }

    size_t mid = arr.size() / 2;

    vector<int> left(arr.begin(), arr.begin() + mid);
    vector<int> right(arr.begin() + mid, arr.end());

    left = merge_sort(left);
    right = merge_sort(right);

    vector<int> merged;
    merged.reserve(arr.size());

    size_t i = 0, j = 0;
    while (i < left.size() && j < right.size()) {
        if (left[i] <= right[j]) {
            merged.push_back(left[i++]);
        } else {
            merged.push_back(right[j++]);
        }
    }

    while (i < left.size()) merged.push_back(left[i++]);
    while (j < right.size()) merged.push_back(right[j++]);

    return merged;
}

int binary_search(vector<int> &arr, int key) {
    vector<int> sorted_arr = merge_sort(arr);

    int left = 0;
    int right = static_cast<int>(sorted_arr.size()) - 1;

    while (left <= right) {
        int mid = left + (right - left) / 2;

        if (sorted_arr[mid] == key)
            return mid;
        else if (sorted_arr[mid] < key)
            left = mid + 1;
        else
            right = mid - 1;
    }

    return -1;
}

